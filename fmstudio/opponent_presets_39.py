def opponent_presets():
    """Retorna {id_1_a_39: {'cartas': [], 'pools': [{'compras': 40, 'pesos': {...}}]}}."""
    if len(_DECK_IDS) != 39:
        raise ModError('Lista de presets incompleta.')
    presets = {}
    for index, line in enumerate(_DECK_IDS, 1):
        ids = [int(part) for part in line.split()]
        weights = _WEIGHT_SETS[0 if index <= 8 else (1 if index <= 24 else 2)]
        if len(ids) != 20 or len(set(ids)) != 20 or len(weights) != 20:
            raise ModError(f'Deck predefinido #{index:02d} inválido.')
        pool = dict(zip(ids, weights))
        if sum(pool.values()) != 2048:
            raise ModError(f'Peso do deck #{index:02d} não soma 2048.')
        presets[str(index)] = {'cartas': [], 'pools': [{'compras': 40, 'pesos': pool}]}
    return presets
